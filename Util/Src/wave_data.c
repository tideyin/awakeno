#include "spi_flash.h"
#include "gd32e10x.h"
#include <string.h>

#define WAV_Q_SIZE   4096u
#define WAV_Q_MASK   (WAV_Q_SIZE - 1u)

static audio_wav_src_t wav_src = AUDIO_WAV_SRC_EMBED;
static uint8_t wav_q[WAV_Q_SIZE];
static volatile uint32_t wav_q_rd;
static volatile uint32_t wav_q_wr;
static uint32_t wav_fetch_pos;
static uint32_t wav_fetch_end;

int audio_wav_read(audio_wav_src_t src, uint32_t off, uint8_t *dst, uint32_t len)
{
	if ((dst == 0) || (len == 0u)) {
		return (len == 0u) ? 0 : -1;
	}
	if (src == AUDIO_WAV_SRC_SPI) {
		return spi_flash_read(AUDIO_WAV_SPI_OFF + off, dst, len);
	}
	if ((off + len) > wavetestdata_size) {
		return -1;
	}
	(void)memcpy(dst, (const uint8_t *)&wavetestdata[off], len);
	return 0;
}

uint32_t audio_wav_read_unit(audio_wav_src_t src, uint32_t *idx,
			     uint8_t nbytes, int little_endian)
{
	uint8_t b[4];
	uint32_t i;
	uint32_t temp = 0;

	if ((idx == 0) || (nbytes == 0u) || (nbytes > 4u)) {
		return 0;
	}
	if (0 != audio_wav_read(src, *idx, b, nbytes)) {
		*idx += nbytes;
		return 0;
	}
	*idx += nbytes;
	if (little_endian) {
		for (i = 0; i < nbytes; i++) {
			temp |= ((uint32_t)b[i]) << (i * 8u);
		}
	} else {
		for (i = 0; i < nbytes; i++) {
			temp = (temp << 8) | (uint32_t)b[i];
		}
	}
	return temp;
}

void audio_wav_stream_fill(void)
{
	uint32_t used;
	uint32_t space;
	uint32_t chunk;
	uint32_t file_left;
	uint32_t to_wrap;
	uint32_t primask;

	while (wav_fetch_pos < wav_fetch_end) {
		primask = __get_PRIMASK();
		__disable_irq();
		used = wav_q_wr - wav_q_rd;
		__set_PRIMASK(primask);

		if (used >= (WAV_Q_SIZE - 1u)) {
			break;
		}
		space = (WAV_Q_SIZE - 1u) - used;
		file_left = wav_fetch_end - wav_fetch_pos;
		chunk = (space < file_left) ? space : file_left;
		/* SPI: larger bursts; IRQ still runs during spi_flash_read waits */
		if ((wav_src == AUDIO_WAV_SRC_SPI) && (chunk > 256u)) {
			chunk = 256u;
		}
		to_wrap = WAV_Q_SIZE - (wav_q_wr & WAV_Q_MASK);
		if (chunk > to_wrap) {
			chunk = to_wrap;
		}
		if (0 != audio_wav_read(wav_src, wav_fetch_pos,
					&wav_q[wav_q_wr & WAV_Q_MASK], chunk)) {
			break;
		}
		primask = __get_PRIMASK();
		__disable_irq();
		wav_q_wr += chunk;
		__set_PRIMASK(primask);
		wav_fetch_pos += chunk;
	}
}

void audio_wav_stream_start(audio_wav_src_t src, uint32_t pcm_off, uint32_t pcm_len)
{
	wav_src = src;
	wav_q_rd = 0;
	wav_q_wr = 0;
	wav_fetch_pos = pcm_off;
	wav_fetch_end = pcm_off + pcm_len;
	audio_wav_stream_fill();
}

void audio_wav_stream_stop(void)
{
	wav_q_rd = 0;
	wav_q_wr = 0;
	wav_fetch_pos = wav_fetch_end;
}

int audio_wav_stream_eof(void)
{
	return ((wav_fetch_pos >= wav_fetch_end) &&
		((wav_q_wr - wav_q_rd) < 2u)) ? 1 : 0;
}

int audio_wav_stream_get16(int16_t *out)
{
	uint8_t lo;
	uint8_t hi;
	uint32_t primask;

	if (out == 0) {
		return -1;
	}

	primask = __get_PRIMASK();
	__disable_irq();
	if ((wav_q_wr - wav_q_rd) < 2u) {
		__set_PRIMASK(primask);
		return -1;
	}
	lo = wav_q[wav_q_rd & WAV_Q_MASK];
	wav_q_rd++;
	hi = wav_q[wav_q_rd & WAV_Q_MASK];
	wav_q_rd++;
	__set_PRIMASK(primask);

	*out = (int16_t)((uint16_t)lo | ((uint16_t)hi << 8));
	return 0;
}

